#!/usr/bin/env python3
"""Label anchors for the baked regions: for every region id one stable surface point (rest pose) + outward normal, written into
drill-anim/models/training-human-v2plus-regions.json under "anchors" (make_table.py keeps them).
Input: a rest-pose bake dump (tools/human-v2plus/regions.mjs --dump; outfit compression, torso base).
Per region: the mesh holding most of its triangles; area-weighted centroid of its triangles (all 3 corners in the region); the anchor
vertex is the one nearest that centroid among the region's interior vertices (graph depth from the region border >= half the max depth,
so the point never sits on a border or in a sliver); normal = area-weighted normal of the anchor's triangle ring, oriented outward.
The runtime (getRegionAnchor in drill-anim/page/human-v2plus-regions.js) re-skins the anchor vertex and its ring for any posed frame.
  PYTHONPATH=/workspace/work/pylib python3 tools/human-v2plus/regions/anchors.py output/rg/dump.json"""
import sys, json, collections, numpy as np
TP = 'drill-anim/models/training-human-v2plus-regions.json'
D = json.load(open(sys.argv[1])); T = json.load(open(TP))
STATE = sys.argv[2] if len(sys.argv) > 2 else '{"outfit":"compression","sleeve":"short","torso":"base"}|torso'
meshes = []
for m in D:
    P = np.array(m['rd'], float).reshape(-1, 4)[:, :3]; L = np.array(m['lab']); F = np.array(m['idx']).reshape(-1, 3)
    a, b, c = P[F[:, 0]], P[F[:, 1]], P[F[:, 2]]; fn = np.cross(b - a, c - a); area = np.linalg.norm(fn, axis=1) / 2
    same = (L[F[:, 0]] == L[F[:, 1]]) & (L[F[:, 1]] == L[F[:, 2]])
    meshes.append(dict(name=m['name'], n=m['n'], P=P, L=L, F=F, fn=fn, area=area, same=same))
# outward check: torso / limb normals should point away from the body's inner axis line (x=0 for the trunk, the limb axes otherwise);
# use the global majority sign per mesh (face winding is consistent per mesh)
def outward_sign(M):
    cen = (M['P'][M['F'][:, 0]] + M['P'][M['F'][:, 1]] + M['P'][M['F'][:, 2]]) / 3
    ref = cen.copy(); ref[:, 1] = cen[:, 1]; ref[:, 0] = 0; ref[:, 2] = 0.0   # trunk axis
    s = np.sign(np.einsum('ij,ij->i', M['fn'], cen - ref)); return 1.0 if (s * M['area']).sum() >= 0 else -1.0
for M in meshes: M['sign'] = outward_sign(M)
anchors = []
for r in T['regions']:
    rid = r['id']; best = None
    for k, M in enumerate(meshes):
        sel = M['same'] & (M['L'][M['F'][:, 0]] == rid); A = M['area'][sel].sum()
        if A > 0 and (best is None or A > best[1]): best = (k, A, sel)
    if best is None: anchors.append(None); continue
    k, A, sel = best; M = meshes[k]; F = M['F'][sel]; P = M['P']
    cen = ((P[F[:, 0]] + P[F[:, 1]] + P[F[:, 2]]) / 3 * M['area'][sel, None]).sum(0) / A
    verts = np.unique(F); vin = set(verts.tolist())
    # adjacency over the whole mesh, depth = BFS hops from region-border vertices (vertices of the region touching another label)
    nb = collections.defaultdict(set)
    tri_any = M['F'][np.isin(M['F'], verts).any(1)]
    for t in tri_any:
        for i in range(3):
            for j in range(3):
                if i != j: nb[int(t[i])].add(int(t[j]))
    border = [v for v in verts.tolist() if any(M['L'][u] != rid for u in nb[v])]
    depth = {v: 0 for v in border}; q = collections.deque(border)
    while q:
        v = q.popleft()
        for u in nb[v]:
            if u in vin and u not in depth: depth[u] = depth[v] + 1; q.append(u)
    for v in verts.tolist(): depth.setdefault(v, 0)
    dmax = max(depth.values()); cand = np.array([v for v in verts.tolist() if depth[v] >= max(1, dmax // 2)] or verts.tolist())
    vi = int(cand[np.argmin(np.linalg.norm(P[cand] - cen, axis=1))])
    ring = M['F'][(M['F'] == vi).any(1)]; rn = (M['fn'][(M['F'] == vi).any(1)]).sum(0) * M['sign']; nrm = rn / np.linalg.norm(rn)
    anchors.append({'id': rid, 'mesh': M['name'], 'meshVerts': M['n'], 'vertex': vi, 'rest': [round(float(x), 4) for x in P[vi]],
                    'normal': [round(float(x), 4) for x in nrm], 'ring': ring[:8].tolist(), 'ringSign': M['sign'],
                    'depth': depth[vi], 'areaCm2': round(float(A) * 1e4, 1)})
T['anchors'] = {'note': 'one label anchor per region id (null = region has no surface in this bake); rest pose, metres; ring = triangles (vertex '
                'indices in that mesh) around the anchor, normal = ringSign * sum of their face normals. Valid for bake state "' + STATE + '". '
                'Generated by tools/human-v2plus/regions/anchors.py.', 'state': STATE, 'list': anchors}
with open(TP, 'w', encoding='utf-8') as f: json.dump(T, f, ensure_ascii=False, indent=1); f.write('\n')
miss = [T['regions'][i]['key'] + T['regions'][i]['side'] for i, a in enumerate(anchors) if a is None]
print('anchors', sum(a is not None for a in anchors), 'missing', miss, 'signs', {M['name']: M['sign'] for M in meshes})
