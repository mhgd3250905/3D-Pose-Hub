 ('rhomboid', '菱形肌区（M4 起并入斜方肌中下部，保留 id）', 'rhomboid area (retired in M4: folded into middle / lower trapezius; id kept)', 'retired'),
 ('infraspinatus', '冈下肌 / 小圆肌', 'infraspinatus / teres minor', 'muscle'),
